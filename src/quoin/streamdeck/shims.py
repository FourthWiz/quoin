"""Rendered entry points: the hook shim, the terminal entry, legacy forwarders and tombstones.

Pure renderers returning text; nothing here touches the filesystem. Every
embedded path goes through `shlex.quote` (shell) or `repr` (Python) so a
runtime directory containing spaces or quotes stays intact. None of the
rendered hook entry points ever `exec`s or exits non-zero on the hook path: a
hook must never block or fail an agent, whatever state the runtime is in.

Python renders are stdlib only and parse as Python 3.9.
"""
import os
import shlex

from . import manifest

HEADER = "# generated by quoin streamdeck; do not edit"
MISSING_MESSAGE = "Quoin Stream Deck runtime is missing; run quoin streamdeck install"
FORWARDER_NAMES = ("monitor.py", "dashboard.py", "controller.py", "terminal.zsh")
TOMBSTONE_KINDS = ("sh", "python")


def _current(runtime, name):
    return os.path.join(runtime, "current", name)


def render_hook_shim(runtime, python):
    """Hook entry point: run the monitor when it is reachable, else just drain stdin; always exit 0."""
    return "\n".join([
        "#!/bin/sh",
        HEADER,
        "QUOIN_DECK_RUNTIME=%s" % shlex.quote(runtime),
        "export QUOIN_DECK_RUNTIME",
        "PY=%s" % (shlex.quote(python) if python else ""),
        't="$QUOIN_DECK_RUNTIME/current/monitor.py"',
        'if [ -r "$t" ] && [ -x "$PY" ]; then',
        '  "$PY" -E -s "$t" "$@" >/dev/null 2>&1',
        "else",
        "  cat >/dev/null 2>&1",
        "fi",
        "exit 0",
        "",
    ])


def render_terminal_entry(runtime):
    """Stable entry the deck launches inside a terminal; hands over to the current terminal script."""
    return "\n".join([
        "#!/bin/sh",
        HEADER,
        "t=%s" % shlex.quote(_current(runtime, "terminal.zsh")),
        'if [ -r "$t" ]; then',
        '  exec /bin/zsh "$t" "$@"',
        "fi",
        'echo %s >&2' % shlex.quote(MISSING_MESSAGE),
        "exit 1",
        "",
    ])


_PY_PRELUDE = '''#!/usr/bin/env python3
%(header)s
import os
import subprocess
import sys

RUNTIME = %(runtime)s
PYTHON = %(python)s
TARGET = os.path.join(RUNTIME, "current", %(name)s)
MISSING = %(missing)s


def interpreter():
    if PYTHON and os.access(PYTHON, os.X_OK):
        return PYTHON
    return sys.executable


def child_env(extra=None):
    env = dict(os.environ)
    env["QUOIN_DECK_RUNTIME"] = RUNTIME
    if extra:
        env.update(extra)
    return env


def drain():
    try:
        if sys.stdin is not None and not sys.stdin.isatty():
            while sys.stdin.buffer.read(65536):
                pass
    except BaseException:
        pass
'''

_MONITOR_BODY = '''

def main():
    try:
        if not os.access(TARGET, os.R_OK):
            drain()
            return 0
        subprocess.run([interpreter(), "-E", "-s", TARGET] + sys.argv[1:], stdin=sys.stdin,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       env=child_env({"QUOIN_DECK_VIA": "legacy"}), timeout=2.5)
    except BaseException:
        pass
    return 0


sys.exit(main())
'''

_DASHBOARD_BODY = '''

def fail(action):
    if action == "snapshot":
        print("[]")
        return 0
    sys.stderr.write("Quoin Stream Deck: the %s action failed\\n" % (action or "requested"))
    return 1


def main():
    action = sys.argv[1] if len(sys.argv) > 1 else ""
    if not os.access(TARGET, os.R_OK):
        return fail(action)
    try:
        proc = subprocess.run([interpreter(), "-E", "-s", TARGET] + sys.argv[1:], stdin=subprocess.DEVNULL,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=child_env(),
                              timeout=20 if action == "snapshot" else None)
    except BaseException:
        return fail(action)
    if proc.returncode != 0:
        return fail(action)
    sys.stdout.flush()
    sys.stdout.buffer.write(proc.stdout)
    sys.stdout.buffer.flush()
    return 0


sys.exit(main())
'''

_CONTROLLER_BODY = '''

def main():
    if not os.access(TARGET, os.R_OK):
        sys.stderr.write(MISSING + "\\n")
        return 1
    try:
        return subprocess.call([interpreter(), "-E", "-s", TARGET] + sys.argv[1:], env=child_env())
    except BaseException:
        sys.stderr.write(MISSING + "\\n")
        return 1


sys.exit(main())
'''

_PY_BODIES = {"monitor.py": _MONITOR_BODY, "dashboard.py": _DASHBOARD_BODY, "controller.py": _CONTROLLER_BODY}


def render_forwarder(name, runtime, python):
    """Stand-in for a prototype root script that forwards to the script in `current/`."""
    if name == "terminal.zsh":
        return "\n".join([
            "#!/bin/zsh",
            HEADER,
            "t=%s" % shlex.quote(_current(runtime, "terminal.zsh")),
            'if [[ ! -r "$t" ]]; then',
            "  print -u2 -- %s" % shlex.quote(MISSING_MESSAGE),
            "  exit 1",
            "fi",
            'exec /bin/zsh "$t" "$@"',
            "",
        ])
    if name not in _PY_BODIES:
        raise ValueError("no forwarder for %r" % (name,))
    prelude = _PY_PRELUDE % {
        "header": HEADER, "runtime": repr(runtime), "python": repr(python), "name": repr(name),
        "missing": repr(MISSING_MESSAGE),
    }
    return prelude + _PY_BODIES[name]


def render_tombstone(kind):
    """Inert stub that replaces a hook entry point after uninstall; drains stdin and exits 0."""
    marker = "# " + manifest.TOMBSTONE_MARKER
    if kind == "sh":
        return "\n".join([
            "#!/bin/sh",
            marker,
            "# Inert stub left by `quoin streamdeck uninstall`; remove it with `uninstall --purge`.",
            "cat >/dev/null 2>&1",
            "exit 0",
            "",
        ])
    if kind == "python":
        return "\n".join([
            "#!/usr/bin/env python3",
            marker,
            "# Inert stub left by `quoin streamdeck uninstall`; remove it with `uninstall --purge`.",
            "import sys",
            "try:",
            "    while sys.stdin.buffer.read(65536):",
            "        pass",
            "except BaseException:",
            "    pass",
            "sys.exit(0)",
            "",
        ])
    raise ValueError("kind must be 'sh' or 'python'")


def entry_points(paths):
    """The files that agents' hook commands can reach; the universal tombstone rule covers these."""
    return {
        "hook_shim": paths.hook_shim,
        "terminal_entry": paths.terminal_entry,
        "root_monitor": os.path.join(paths.runtime, "monitor.py"),
    }
