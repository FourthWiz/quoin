"""The plugin folders must ignore node_modules left behind by plugin tooling."""
from pathlib import Path

GITIGNORE = Path(__file__).resolve().parents[3] / ".gitignore"


def test_gitignore_covers_plugin_node_modules():
    rules = [ln.strip() for ln in GITIGNORE.read_text().splitlines()]
    assert any(
        r.startswith("quoin/plugins/") and "node_modules" in r for r in rules
    )
