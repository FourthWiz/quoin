"""Pins the always-on core rules text (quoin/CLAUDE.core.md) and its slim composition.

Two operands per rule: the core text and the committed slim file are both read
from disk, and the full-source paragraph behind each rule is checked in the
generated catalog, so the terse core cannot drift away from the full rules.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[3]
_SOURCE_ROOT = _REPO_ROOT / "quoin"
CORE = _SOURCE_ROOT / "CLAUDE.core.md"
SLIM = _SOURCE_ROOT / "CLAUDE.slim.md"
SOURCE = _SOURCE_ROOT / "CLAUDE.md"
CATALOG = _SOURCE_ROOT / "memory" / "workflow-catalog.md"
INSTALLER = _REPO_ROOT / "src" / "quoin" / "installer.py"

CORE_BYTE_CEILING = 2048
FLOW = (
    "/discover → /specify → GATE → /architect → GATE → /thorough_plan → "
    "GATE → /implement → GATE → /review → GATE → /end_of_task"
)

# rule name -> tokens that must appear in both the core and the slim file
RULE_TOKENS = {
    "flow": [FLOW],
    "explicit-commands": ["/implement", "/end_of_task", "auto-invoke", "/run", "autonomous-mode.md", "/pr"],
    "git": ["push", "/end_of_task", "/pr", "fresh branch", "main/master"],
    "artifacts": [".workflow_artifacts/<task-name>/", "finalized/", "root per project"],
    "shipped-text": ["clean-authored-content.md"],
    "lessons": ["lessons-learned.md", "MEMORY.md", "insights-"],
    "serena": ["serena-activation.md"],
}

# rule name -> literal paragraph/phrase of the full rules that must be in the catalog
CATALOG_ANCHORS = {
    "flow": FLOW,
    "explicit-commands": "No skill may auto-invoke either.",
    "git": "**Never push to remote or create PRs outside of `/end_of_task` and `/pr`.**",
    "artifacts": "IMPORTANT: Never move to `finalized/` during planning or implementation",
    "shipped-text": "Clean authored content.",
    "lessons": "Daily insight capture",
    "serena": "### Serena (conditional)",
}


def _core() -> str:
    return CORE.read_text(encoding="utf-8")


def _slim() -> str:
    return SLIM.read_text(encoding="utf-8")


def test_core_is_small_headingless_and_free_of_plan_vocabulary():
    text = _core()
    assert 0 < len(text.encode("utf-8")) <= CORE_BYTE_CEILING
    assert not [ln for ln in text.split("\n") if re.match(r"^#{1,6} ", ln)]
    assert "pollution_score" not in text
    assert "claude-adapter-optimization" not in text
    for ln in text.split("\n"):
        assert not ("autonomous" in ln and "hooks/" in ln), ln


@pytest.mark.parametrize("rule", sorted(RULE_TOKENS))
def test_rule_tokens_present_in_core_and_slim(rule):
    core, slim = _core(), _slim()
    for token in RULE_TOKENS[rule]:
        assert token in core, f"{rule}: {token!r} missing from CLAUDE.core.md"
        assert token in slim, f"{rule}: {token!r} missing from CLAUDE.slim.md"


@pytest.mark.parametrize("rule", sorted(CATALOG_ANCHORS))
def test_full_rule_text_behind_each_core_rule_is_in_catalog(rule):
    assert CATALOG_ANCHORS[rule] in CATALOG.read_text(encoding="utf-8"), rule


def test_lessons_pointer_in_core_and_full_source():
    assert "lessons-learned.md" in _core() and "MEMORY.md" in _core()
    text = SOURCE.read_text(encoding="utf-8")
    start = text.index("### Lessons learned")
    nxt = re.search(r"^#{1,3} ", text[start + 5:], re.M)
    section = text[start:start + 5 + nxt.start()] if nxt else text[start:]
    assert section.strip()
    assert "The file `.workflow_artifacts/memory/lessons-learned.md` accumulates" in section
    assert "lessons-learned.md" in section and "MEMORY.md" in section


def test_slim_composition_header_core_and_topic_guide_line():
    slim = _slim()
    assert slim.startswith("<!-- generated by quoin/scripts/build_claude_slim.py")
    assert _core().rstrip("\n") in slim
    last = slim.rstrip("\n").split("\n")[-1]
    assert last.startswith("Topic guides (same folder): ")


def _tier1_files() -> list[str]:
    tree = ast.parse(INSTALLER.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "TIER1_MEMORY_FILES":
                    return [e.value for e in node.value.elts if isinstance(e, ast.Constant)]
    return []


def _named_guides(core_text: str) -> list[str]:
    return sorted(
        {m.group(1) for m in re.finditer(r"(?<![\w/.<>-])([A-Za-z][\w-]*\.md)\b", core_text)} - {"MEMORY.md"}
    )


def test_core_named_memory_files_are_in_topic_guide_line_and_deployed_set():
    named = _named_guides(_core())
    assert named, "the core names no memory guides; the scan is vacuous"
    last = _slim().rstrip("\n").split("\n")[-1]
    tier1 = _tier1_files()
    assert tier1
    for name in named:
        assert name in last.split(": ", 1)[1].split(", "), name
        assert name in tier1, f"{name} is not in TIER1_MEMORY_FILES"


def test_membership_assertion_fails_on_a_core_naming_a_bogus_file():
    import sys

    sys.path.insert(0, str(_SOURCE_ROOT / "scripts"))
    import build_claude_slim as bcs

    bogus_core = _core() + "- **Extra:** see `bogus-guide.md`.\n"
    slim, _catalog = bcs.build_outputs(SOURCE.read_text(encoding="utf-8"), bogus_core)
    assert "bogus-guide.md" in slim.rstrip("\n").split("\n")[-1]
    assert "bogus-guide.md" not in _tier1_files()
