class ClassificationError(RuntimeError):
    """Fail-closed error: source headings and CLASSIFICATION disagree."""


def _fence_aware_headings(text: str) -> list[tuple[int, str]]:
    """Return [(byte_offset, heading_line), ...] for real (non-fenced) H1-H3s."""
    lines = text.split("\n")
    in_fence = False
    offsets: list[tuple[int, str]] = []
    byte_pos = 0
    seen: set[str] = set()
    for ln in lines[:-1]:  # split("\n") on a trailing-newline file ends with ""
        stripped = ln.lstrip()
        if stripped.startswith("```"):
            in_fence = not in_fence
        elif not in_fence and re.match(r"^#{1,3} ", ln):
            if ln in seen:
                raise ClassificationError(f"duplicate heading text in source: {ln!r}")
            seen.add(ln)
            offsets.append((byte_pos, ln))
        byte_pos += len(ln.encode("utf-8")) + 1
    return offsets


def parse_sections(text: str) -> list[tuple[str, int, str]]:
    """Return [(heading, byte_size, section_text), ...] in source order."""
    raw = text.encode("utf-8")
    headings = _fence_aware_headings(text)
    headings.append((len(raw), "<EOF>"))
    sections = []
    for i in range(len(headings) - 1):
        start, heading = headings[i]
        end, _ = headings[i + 1]
        section_bytes = raw[start:end]
        sections.append((heading, len(section_bytes), section_bytes.decode("utf-8")))
    return sections


def classify(sections: list[tuple[str, int, str]]) -> None:
    """Fail-closed bijectivity check between source headings and CLASSIFICATION."""
    source_headings = {h for h, _, _ in sections}
    table_headings = set(CLASSIFICATION.keys())

    missing = source_headings - table_headings
    if missing:
        raise ClassificationError(
            f"{len(missing)} source heading(s) have no CLASSIFICATION entry "
            f"(fail-closed, roster-drift direction): {sorted(missing)!r}"
        )
    orphan = table_headings - source_headings
    if orphan:
        raise ClassificationError(
            f"{len(orphan)} CLASSIFICATION entr(y/ies) have no matching source "
            f"heading (orphan-entry direction): {sorted(orphan)!r}"
        )


def build_outputs(source_text: str) -> tuple[str, str]:
    """Return (slim_text, catalog_text)."""
    sections = parse_sections(source_text)
    classify(sections)

    keep_parts: list[str] = []
    drop_parts: list[str] = []
    index_rows: list[str] = []

    for heading, _size, section_text in sections:
        cls, target = CLASSIFICATION[heading]
        if cls == "keep":
            keep_parts.append(section_text)
        else:
            drop_parts.append(section_text)
            index_rows.append(f"- {heading} -> {target}\n")

    slim_text = SLIM_HEADER + "".join(keep_parts)
    # Each kept section already ends with a trailing blank line (the section
    # byte-span runs up to the next heading). Normalize to exactly one
    # trailing blank line before the index, regardless of how many blank
    # lines happened to trail the final kept section.
    slim_text = slim_text.rstrip("\n") + "\n\n"
    slim_text += INDEX_HEADER + "".join(index_rows)

    catalog_text = CATALOG_HEADER + "".join(drop_parts)

    return slim_text, catalog_text


def run_census(source_text: str) -> str:
    sections = parse_sections(source_text)
    lines = []
    keep_total = 0
    drop_total = 0
    for heading, size, _text in sections:
        cls = CLASSIFICATION.get(heading, ("???", None))[0]
        if cls == "keep":
            keep_total += size
        elif cls == "drop":
            drop_total += size
        lines.append(f"{cls:5} {size:6} {heading}")
    lines.append("---")
    lines.append(f"heading count = {len(sections)}")
    lines.append(f"keep_bytes = {keep_total}")
    lines.append(f"drop_bytes = {drop_total}")
    lines.append(f"sum = {keep_total + drop_total} vs file total {len(source_text.encode('utf-8'))}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="verify committed outputs match regen")
    group.add_argument("--dry-run", action="store_true", help="print outputs, write nothing")
    group.add_argument("--census", action="store_true", help="print the mechanical heading/byte table")
    args = parser.parse_args(argv)

    # Deployed-copy read guard (review round-1 minor): the installed copy at
    # ~/.claude/scripts/ resolves _REPO_ROOT to $HOME, where quoin/CLAUDE.md
    # normally does not exist. Abort cleanly instead of raising. NOTE: this
    # absence test alone does NOT protect a real checkout at $HOME/quoin from
    # being overwritten — that protection is the positive write-mode guard
    # further below (round-2 minor 2).
    if not SOURCE.exists():
        print(
            f"build_claude_slim: source not found at {SOURCE} — this script must "
            "run from the quoin repo checkout (repo-authoring tool, not a "
            "runtime helper). Nothing was read or written.",
            file=sys.stderr,
        )
        return 2

    source_text = SOURCE.read_text(encoding="utf-8")

    if args.census:
        try:
            sys.stdout.write(run_census(source_text))
        except ClassificationError as exc:
            print(f"build_claude_slim: {exc}", file=sys.stderr)
            return 1
        return 0

    try:
        slim_text, catalog_text = build_outputs(source_text)
    except ClassificationError as exc:
        print(f"build_claude_slim: {exc}", file=sys.stderr)
        # Distinguish the two fail-closed directions for the exit code.
        if "orphan-entry" in str(exc):
            return 2
        if "duplicate heading" in str(exc):
            return 3
        return 1

    if args.dry_run:
        sys.stdout.write("=== CLAUDE.slim.md ===\n")
        sys.stdout.write(slim_text)
        sys.stdout.write("\n=== memory/workflow-catalog.md ===\n")
        sys.stdout.write(catalog_text)
        return 0

    if args.check:
        stale = []
        if not SLIM_OUTPUT.exists() or SLIM_OUTPUT.read_text(encoding="utf-8") != slim_text:
            stale.append(str(SLIM_OUTPUT))
        if not CATALOG_OUTPUT.exists() or CATALOG_OUTPUT.read_text(encoding="utf-8") != catalog_text:
            stale.append(str(CATALOG_OUTPUT))
        if stale:
            print(
                "build_claude_slim --check: stale generated file(s): " + ", ".join(stale),
                file=sys.stderr,
            )
            return 7
        return 0

    # POSITIVE write-mode guard (review round-2 minor 2): the round-1
    # source-absence test passed whenever <inferred-root>/quoin/CLAUDE.md
    # happened to exist — e.g. the deployed copy at ~/.claude/scripts/ with a
    # real checkout at ~/quoin — and then silently overwrote that checkout's
    # generated files. Before WRITING (read-only modes above are unaffected),
    # require positive evidence that this file IS the checkout's own copy:
    # samefile with <repo>/quoin/scripts/build_claude_slim.py. A deployed copy
    # can never satisfy this, regardless of what exists under the inferred root.
    expected_self = _SOURCE_ROOT / "scripts" / "build_claude_slim.py"
    self_path = Path(__file__).resolve()
    if not (expected_self.exists() and self_path.samefile(expected_self)):
        print(
            f"build_claude_slim: refusing to write — this copy at {self_path} "
            f"is not the checkout copy at {expected_self} (deployed copies "
            "must never overwrite a checkout's generated files). Nothing was "
            "written.",
            file=sys.stderr,
        )
        return 2

    SLIM_OUTPUT.write_text(slim_text, encoding="utf-8")
    CATALOG_OUTPUT.write_text(catalog_text, encoding="utf-8")
    print(f"Wrote {SLIM_OUTPUT}")
    print(f"Wrote {CATALOG_OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
