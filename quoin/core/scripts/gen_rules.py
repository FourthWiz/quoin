#!/usr/bin/env python3
"""gen_rules.py - path-scoped Claude Code rules from the interface graph.

Writes one ``.claude/rules/quoin-interface-<id>.md`` per interface, at the
project root. Its ``paths:`` globs are the provider's defining paths, so Claude
Code loads it when a session works on those files, and its body names the
consumers to check. Every file carries a generated-file header; files with
that header that no longer match an interface are removed, and no other rule
file is touched.

Usage
  python3 gen_rules.py [--project-root DIR] [--if-dirty]

  --if-dirty  act only when the discovery-dirty marker is newer than the last
              generation; then regenerate the discovery map and
              dependencies-map.md first, so the rules follow the new graph.
              The plugin's SessionStart hook runs this in the background.

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
import interfaces as ifx  # noqa: E402

PREFIX = "quoin-interface-"
HEADER = "<!-- Generated by quoin gen_rules.py from the interface graph. Do not edit; rerun /discover or gen_rules.py. -->"


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:80] or "interface"


def _project_glob(repo_path: str, pattern: str) -> str:
    return pattern if repo_path in (".", "") else f"{repo_path}/{pattern}"


def rule_text(item: dict, repo_paths: dict[str, str]) -> str:
    globs = [_project_glob(repo_paths.get(item["provider"], item["provider"]), p) for p in item["provider_paths"]]
    lines = ["---", "paths:"] + [f'  - "{g}"' for g in globs] + ["---", HEADER, "", f"# Interface: {item['name']}", ""]
    lines.append(
        f"These files define {item['name']} ({item['kind']} interface), which {item['provider']} provides. "
        "Other repositories depend on it:"
    )
    lines.append("")
    for consumer in item["consumers"]:
        where = repo_paths.get(consumer["repo"], consumer["repo"])
        paths = ", ".join(_project_glob(where, p) for p in consumer["paths"])
        lines.append(f"- {consumer['repo']}: {paths}")
    lines += [
        "",
        "When a change alters the interface (names, paths, fields, types, status codes or topics), "
        "check these consumers and keep them working, or change them in the same task.",
        "",
    ]
    return "\n".join(lines)


def generate(project_root: str | Path) -> dict:
    root = Path(project_root).resolve()
    graph = ifx.load_interfaces(root)
    repo_paths = {r["name"]: r["path"] for r in ifx.repositories(root)}
    rules = root / ".claude" / "rules"
    wanted = {f"{PREFIX}{_slug(item['id'])}.md": rule_text(item, repo_paths) for item in graph}
    written, removed = [], []
    if wanted:
        rules.mkdir(parents=True, exist_ok=True)
    for name, text in wanted.items():
        path = rules / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(name)
    if rules.is_dir():
        for path in rules.glob(f"{PREFIX}*.md"):
            if path.name not in wanted and HEADER in path.read_text(encoding="utf-8", errors="replace"):
                path.unlink()
                removed.append(path.name)
    stamp = root / ".workflow_artifacts" / ".capture" / "rules-generated"
    if (root / ".workflow_artifacts").is_dir():
        stamp.parent.mkdir(parents=True, exist_ok=True)
        if not (stamp.parent / ".gitignore").exists():
            (stamp.parent / ".gitignore").write_text("*\n", encoding="utf-8")
        stamp.write_text(json.dumps({"interfaces": len(graph)}), encoding="utf-8")
    return {"interfaces": len(graph), "written": written, "removed": removed}


def is_dirty(root: Path) -> bool:
    marker = root / ".workflow_artifacts" / "memory" / "discovery-dirty"
    stamp = root / ".workflow_artifacts" / ".capture" / "rules-generated"
    if not marker.is_file():
        return False
    return not stamp.is_file() or marker.stat().st_mtime > stamp.stat().st_mtime


def refresh(project_root: str | Path) -> dict:
    """Regenerate the discovery map and dependencies map, then the rules."""
    import generate_discovery_map as gdm

    root = Path(project_root).resolve()
    gdm.write_map(gdm.generate_map(root), ifx.map_path(root))
    ifx.write_dependencies_map(root)
    return generate(root)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--project-root", default=".")
    parser.add_argument("--if-dirty", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.project_root).resolve()
    if args.if_dirty:
        if not is_dirty(root):
            print(json.dumps({"skipped": "discovery is not dirty"}))
            return 0
        print(json.dumps(refresh(root)))
        return 0
    print(json.dumps(generate(root)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
